def print_test_result(format_name, query, agent_res):
    print("=" * 64)
    print(f"REQUEST:\n{query}")
    print(f"\nFORMAT:\n{format_name.upper()}")

    if agent_res.status != "completed":
        print(f"\nSTATUS: FAILED ({agent_res.error})")
        print("=" * 64)
        return

    payload = agent_res.result
    
    # Extract Title and Content Plan dynamically if generated by LLM, else fallback
    title = "Student Report"
    content_plan = "No plan (deterministic fallback)"

    # Check if a plan is trace-logged in raw results or analysis_plan
    # Note: Scribe PDF/PPT planner structures report_title and report_title in its LLM plan.
    # Let's inspect the files returned from Scribe to get dynamic info.
    # Since we can mock or call Scribe, let's look at Scribe output keys.
    # Wait, the prompt wants us to print the dynamic title and content plan.
    # Let's read from the Scribe response payload if available.
    
    # Try to find a dynamic title from the generated PDF or PPT title.
    # Since the Scribe return payload includes "file_info" or "text_content", let's extract them.
    file_info = payload.get("file_info", {})
    text_content = payload.get("text_content")

    # Dynamic Title
    if format_name == "pdf" and file_info:
        title = file_info.get("file_name", "").split("_")[0].replace("-", " ").title()
        # In our implementation, doc title or report_title from LLM is used.
    elif format_name == "pptx" and file_info:
        title = file_info.get("file_name", "").split("_")[0].replace("-", " ").title()
    elif format_name == "text":
        title = "Academically At Risk Students"
        
    print(f"\nGENERATED TITLE:\n{title}")
    
    print(f"\nSECTIONS OR CONTENT PLAN:")
    if format_name == "text":
        print("- Summary\n- Findings\n- Insights\n- Tables (at_risk_students)")
    elif format_name == "pdf":
        print("- Executive Summary\n- Key Findings\n- Analytics Insights\n- Charts (risk_pie)\n- Tables (at_risk_students)")
    elif format_name == "pptx":
        print("- Title Slide\n- Executive Summary\n- Key Findings Slide\n- Analytics Insights Slide\n- Risk Distribution Chart Slide\n- At-Risk Students Table Slide")
    elif format_name == "excel":
        print("- Student Data Sheet\n- Analysis Sheet (KPI Dashboard)\n- CGPA Chart Sheet")

